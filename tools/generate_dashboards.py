class Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def main(out_dir: Path) -> None:
    for lang, reve, name in (
        (0, False, "dashboard.yaml"),
        (1, False, "dashboard-uk.yaml"),
        (0, True, "dashboard-reve.yaml"),
        (1, True, "dashboard-reve-uk.yaml"),
    ):
        body = yaml.dump(build(lang, reve), Dumper=Dumper, allow_unicode=True, sort_keys=False, width=200)
        header = [*(REVE_HEADERS if reve else HEADERS)[lang], GENERATED]
        (out_dir / name).write_text("\n".join(header) + "\n" + body, encoding="utf-8")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "docs")
